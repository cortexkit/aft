#[cfg(test)]
mod tests {
    use super::read_path_template;

    #[test]
    fn read_path_template_redacts_values_and_keeps_path_literals() {
        for (path, expected) in [
            ("/repos/actions/jobs", "/repos/{owner}/{repo}"),
            (
                "/repos/Owner/Repo/pulls/42/comments?private_query=secret#fragment",
                "/repos/{owner}/{repo}/pulls/{n}/comments",
            ),
            (
                "/repos/Owner/Repo/commits/0123456789abcdef0123456789abcdef01234567/check-runs",
                "/repos/{owner}/{repo}/commits/{sha}/check-runs",
            ),
            (
                "/repos/Owner/Repo/git/blobs/0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef",
                "/repos/{owner}/{repo}/git/blobs/{sha}",
            ),
            (
                "/repos/Owner/Repo/branches/Feature/HotFix",
                "/repos/{owner}/{repo}/branches/{x}/{x}",
            ),
            (
                "/repos/Owner/Repo/branches/Feature%2FHotFix",
                "/repos/{owner}/{repo}/branches/{x}",
            ),
            (
                "/repos/Owner/Repo/branches/main",
                "/repos/{owner}/{repo}/branches/{x}",
            ),
            (
                "/repos/Owner/Repo/contents/src/lib/main.rs?ref=private",
                "/repos/{owner}/{repo}/contents/{x}/{x}/{x}",
            ),
            (
                "/repos/Owner/Repo/labels/security#private",
                "/repos/{owner}/{repo}/labels/{x}",
            ),
            ("/users/SomeName/٢/comments", "/users/{x}/{x}/comments"),
        ] {
            assert_eq!(read_path_template(path), expected, "{path}");
        }
    }
}
