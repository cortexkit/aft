pub(super) fn read_path_template(path: &str) -> String {
    let path = path.split(['?', '#']).next().unwrap_or_default();
    let path = path.strip_prefix('/').unwrap_or(path);
    let repo_relative = path.starts_with("repos/");
    let mut template = String::new();
    for (index, segment) in path.split('/').enumerate() {
        template.push('/');
        template.push_str(match (repo_relative, index) {
            (true, 1) => "{owner}",
            (true, 2) => "{repo}",
            _ => template_segment(segment),
        });
    }
    template
}

fn template_segment(segment: &str) -> &str {
    if !segment.is_empty() && segment.bytes().all(|byte| byte.is_ascii_digit()) {
        "{n}"
    } else if matches!(segment.len(), 40 | 64)
        && segment
            .bytes()
            .all(|byte| byte.is_ascii_digit() || matches!(byte, b'a'..=b'f'))
    {
        "{sha}"
    } else if REPO_PATH_LITERALS.contains(&segment) {
        segment
    } else {
        "{x}"
    }
}

