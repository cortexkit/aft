#!/usr/bin/env python3
"""Byte-check a write-only generator and always restore the caller's files."""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


def contents(root):
    return {p.relative_to(root): p.read_bytes() for p in root.rglob("*") if p.is_file()}


def check(root, command):
    scratch = Path("target/scratch")
    scratch.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="prepush-generated-", dir=scratch) as temp:
        backup = Path(temp) / "original"
        shutil.copytree(root, backup, symlinks=True)
        before = contents(root)
        try:
            result = subprocess.run(command, check=False)
            after = contents(root)
        finally:
            shutil.rmtree(root)
            shutil.copytree(backup, root, symlinks=True)
        changed = sorted(str(p) for p in before.keys() | after.keys() if before.get(p) != after.get(p))
        if changed:
            print("Generated bytes differ (original files restored):", file=sys.stderr)
            for path in changed:
                print(f"  {root / path}", file=sys.stderr)
        else:
            print(f"Compared {len(before)} generated files byte for byte; originals restored")
        return result.returncode or bool(changed)


if __name__ == "__main__":
    if len(sys.argv) < 5 or sys.argv[2] != "--":
        raise SystemExit("usage: check-generated.py <directory> -- <generator> [args...]")
    raise SystemExit(check(Path(sys.argv[1]), sys.argv[3:]))
