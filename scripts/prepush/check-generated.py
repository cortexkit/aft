#!/usr/bin/env python3
"""Byte-check a write-only generator and always restore the caller's files."""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


def contents(root):
    if root.is_file():
        return {Path(): root.read_bytes()}
    return {p.relative_to(root): p.read_bytes() for p in root.rglob("*") if p.is_file()}


def check(root, command):
    roots = root if isinstance(root, list) else [root]
    scratch = Path("target/scratch")
    scratch.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="prepush-generated-", dir=scratch) as temp:
        backups = [Path(temp) / str(index) for index in range(len(roots))]
        before = {}
        for source, backup in zip(roots, backups):
            if source.is_dir():
                shutil.copytree(source, backup, symlinks=True)
            else:
                shutil.copy2(source, backup, follow_symlinks=False)
            before.update({source / p: data for p, data in contents(source).items()})
        if not before:
            raise ValueError(f"No generated files found under {roots}; check did not run")
        try:
            result = subprocess.run(command, check=False)
            after = {source / p: data for source in roots for p, data in contents(source).items()}
        finally:
            for source, backup in zip(roots, backups):
                if source.is_dir():
                    shutil.rmtree(source)
                elif source.exists() or source.is_symlink():
                    source.unlink()
                if backup.is_dir():
                    shutil.copytree(backup, source, symlinks=True)
                else:
                    shutil.copy2(backup, source, follow_symlinks=False)
        changed = sorted(str(p) for p in before.keys() | after.keys() if before.get(p) != after.get(p))
        if changed:
            print("Generated bytes differ (original files restored):", file=sys.stderr)
            for path in changed:
                print(f"  {path}", file=sys.stderr)
        else:
            print(f"Compared {len(before)} generated files byte for byte; originals restored")
        return result.returncode or bool(changed)


if __name__ == "__main__":
    if "--" not in sys.argv:
        raise SystemExit("usage: check-generated.py <file-or-directory>... -- <generator> [args...]")
    separator = sys.argv.index("--")
    if separator < 2 or separator == len(sys.argv) - 1:
        raise SystemExit("both generated paths and a generator are required")
    raise SystemExit(check([Path(p) for p in sys.argv[1:separator]], sys.argv[separator + 1:]))
