#!/usr/bin/env python3
"""Byte-check a generator using AFT_GENERATED_OUTPUT_DIR, without changing inputs.

Output paths are relative to the common root of the inputs: a directory input
uses itself as its root, while a file input uses its parent directory.
"""
import os
import subprocess
import sys
import tempfile
from pathlib import Path


def contents(root):
    if root.is_file():
        return {Path(): root.read_bytes()}
    return {p.relative_to(root): p.read_bytes() for p in root.rglob("*") if p.is_file()}


def check(root, command):
    roots = root if isinstance(root, list) else [root]
    base = Path(os.path.commonpath([p if p.is_dir() else p.parent for p in roots]))
    before = {source / p: data for source in roots for p, data in contents(source).items()}
    if not before:
        raise ValueError(f"No generated files found under {roots}; check did not run")
    expected = {p.relative_to(base): data for p, data in before.items()}
    scratch = Path("target/scratch")
    scratch.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="prepush-generated-", dir=scratch) as temp:
        output = Path(temp).resolve()
        result = subprocess.run(command, check=False, env={**os.environ, "AFT_GENERATED_OUTPUT_DIR": str(output)})
        after = contents(output)
        if not after:
            print(f"No generated files found under {output}; check did not run", file=sys.stderr)
            return result.returncode or 1
        changed = sorted(str(base / p) for p in expected.keys() | after.keys() if expected.get(p) != after.get(p))
        if changed:
            print("Generated bytes differ:", file=sys.stderr)
            for path in changed:
                print(f"  {path}", file=sys.stderr)
        else:
            print(f"Compared {len(before)} generated files byte for byte; inputs unchanged")
        return result.returncode or bool(changed)


if __name__ == "__main__":
    if "--" not in sys.argv:
        raise SystemExit("usage: check-generated.py <file-or-directory>... -- <generator> [args...]")
    separator = sys.argv.index("--")
    if separator < 2 or separator == len(sys.argv) - 1:
        raise SystemExit("both generated paths and a generator are required")
    raise SystemExit(check([Path(p) for p in sys.argv[1:separator]], sys.argv[separator + 1:]))
